#!/usr/bin/env python3
"""Generate Markdown pages from the data files.

Writes docs/matrix.md, docs/tools/<tool>.md and a copy of the schema under
docs/schema/. These files are build output: do not edit them by hand. Also refreshes the generated navigation block in
zensical.toml so every tool page is listed.
"""

import json
import os
import re
import shutil
import sys

from common import (
    ROOT,
    SCHEMA_FILE,
    cell,
    format_range,
    load_window,
    load_yaml,
    release_key,
    release_label,
    tool_files,
    version_key,
)

DOCS = ROOT / "docs"
SITE_CONFIG = ROOT / "zensical.toml"
HEADER = "<!-- Generated by scripts/generate.py. Do not edit. -->\n\n"


def front_matter(description):
    """YAML front matter giving the page its own meta and social preview description."""
    return "---\ndescription: " + json.dumps(description) + "\n---\n\n"


def window_text(window):
    ordered = sorted(window, key=version_key)
    return ", ".join(ordered[:-1]) + " and " + ordered[-1]

CATEGORY_TITLES = {
    "backup-storage": "Backup, storage and data",
    "networking": "Networking and ingress",
    "gitops-delivery": "GitOps and delivery",
    "security": "Security and secrets",
    "observability-policy-scaling": "Observability, policy and scaling",
    "workloads-runtimes": "Workloads and runtimes",
    "cluster-lifecycle": "Cluster lifecycle",
}


def badge(level):
    """A claim level as a styled label (see docs/stylesheets/extra.css)."""
    return f'<span class="k8s-level k8s-{level}">{level}</span>'


def format_cell(level, detail):
    if level == "tested":
        return f'{badge(level)} <span class="k8s-detail">{detail}</span>'
    return badge(level)


def current(releases):
    return sorted(
        (r for r in releases if "delisted" not in r),
        key=release_key,
        reverse=True,
    )


def delisted(releases):
    return sorted(
        (r for r in releases if "delisted" in r),
        key=release_key,
        reverse=True,
    )


def in_window(releases, window):
    """Releases with at least one upstream claim covering the window."""
    return [r for r in releases if any(cell(r, m, window)[0] != "unknown" for m in window)]


def matrix_table(title, releases, window):
    lines = [
        f"| {title} | " + " | ".join(f"Kubernetes {m}" for m in window) + " |",
        "|---|" + "---|" * len(window),
    ]
    for release in releases:
        cells = [format_cell(*cell(release, minor, window)) for minor in window]
        lines.append(f"| {release_label(release)} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def format_unsupported(release):
    items = [i if isinstance(i, str) else format_range(i) for i in release.get("unsupported", [])]
    return ", ".join(items) or "none stated"


def provenance_table(releases):
    """What upstream states per release. Columns no release uses are left out."""
    columns = [("Version", release_label)]
    if any(r.get("tested") for r in releases):
        columns.append(("Tested on", lambda r: ", ".join(sorted(r.get("tested", []), key=version_key)) or "none stated"))
    if any(r.get("stated") for r in releases):
        columns.append(("Stated range", stated_cell))
    if any(r.get("unsupported") for r in releases):
        columns.append(("Stated unsupported", format_unsupported))
    columns.append(("Source", source_cell))
    columns.append(("Verified", lambda r: date_cell(r["verified"])))
    lines = [
        "| " + " | ".join(title for title, _ in columns) + " |",
        "|" + "---|" * len(columns),
    ]
    for release in releases:
        lines.append("| " + " | ".join(render(release) for _, render in columns) + " |")
    return "\n".join(lines)


def stated_cell(release):
    stated = release.get("stated")
    if not stated:
        return "none stated"
    return f"{format_range(stated)}<br><span class=\"k8s-wording\">\"{stated['wording']}\"</span>"


def date_cell(date):
    return f'<span class="k8s-date">{date}</span>'


def source_cell(release):
    """One link to the statement, permanent where the source is a file in a repository."""
    source, commit = release["source"], release.get("source_commit")
    if not commit:
        return f"[upstream]({source})"
    readme = re.fullmatch(r"(https://github\.com/[^/]+/[^/#]+)#(.+)", source)
    if "/blob/" in source:
        source = re.sub(r"/blob/[^/]+/", f"/blob/{commit}/", source, count=1)
    elif readme:  # a repository link with an anchor points into its README
        source = f"{readme.group(1)}/blob/{commit}/README.md#{readme.group(2)}"
    return f"[upstream at {commit[:7]}]({source})"


def tool_page(tool, window):
    description = (f"Which {tool['title']} versions work with Kubernetes {window_text(window)}, "
                   "as stated by its maintainers, with links to the upstream source.")
    parts = [front_matter(description) + HEADER, f"# {tool['title']}\n"]
    parts.append(f"Upstream repository: <{tool['repo']}>\n")
    if tool.get("notes"):
        parts.append(tool["notes"].strip() + "\n")

    active = current(tool["releases"])
    if active:
        parts.append("## Current Kubernetes versions\n")
        covered = in_window(active, window)
        if covered:
            parts.append(matrix_table(f"{tool['title']} version", covered, window) + "\n")
        else:
            parts.append(
                "No recorded version has an upstream statement covering Kubernetes "
                + ", ".join(window) + ".\n"
            )
        older = len(active) - len(covered)
        if covered and older:
            parts.append(
                f"{older} other recorded version{'s have' if older > 1 else ' has'} no upstream statement "
                "covering these Kubernetes versions, so every cell would read unknown. "
                f"{'They are' if older > 1 else 'It is'} listed in the next table.\n"
            )
        parts.append("See [how to read this](../how-to-read.md) for what each level means.\n")
        parts.append("## What upstream states\n")
        parts.append(provenance_table(active) + "\n")

    old = delisted(tool["releases"])
    if old:
        parts.append("## No longer listed upstream\n")
        parts.append(
            "Upstream has removed these rows from its compatibility statement. "
            "The values below are the last ones it published.\n"
        )
        lines = ["| Version | Tested on | Stated range | Last listed at | Delisted |", "|---|---|---|---|---|"]
        for release in old:
            tested = ", ".join(sorted(release.get("tested", []), key=version_key)) or "none stated"
            lines.append(
                f"| {release_label(release)} | {tested} | {stated_cell(release)} | "
                f"{source_cell(release)} | {date_cell(release['delisted'])} |"
            )
        parts.append("\n".join(lines) + "\n")

    return "\n".join(parts)


def jump_list(by_category):
    """One line per category linking to each tool's section, for finding a tool without scrolling."""
    lines = []
    for category, title in CATEGORY_TITLES.items():
        group = sorted(by_category.get(category, []), key=lambda t: t["title"].lower())
        if group:
            links = " · ".join(f"[{tool['title']}](#{tool['name']})" for tool in group)
            lines.append(f"**{title}:** {links}")
    return "\n\n".join(lines) + "\n"


def matrix_page(tools, window):
    description = (f"Compatibility of {len(tools)} Kubernetes tools with Kubernetes {window_text(window)}, "
                   "with every claim linked to its upstream source.")
    parts = [front_matter(description) + HEADER, "# Compatibility matrix\n"]
    parts.append(
        "Kubernetes " + ", ".join(window) + ". "
        "See [how to read this](how-to-read.md) for what each level means.\n"
    )
    oldest = min(r["verified"] for tool in tools for r in tool["releases"])
    checked = os.environ.get("UPSTREAM_CHECKED", "").strip()
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", checked):  # set by pages.yml from the latest successful daily detect.yml run
        parts.append(f"{len(tools)} tools. Upstream last checked on {checked}.\n")
    else:  # local builds: no detect run to refer to
        parts.append(f"{len(tools)} tools. Every entry was last checked against its upstream source on or after {oldest}.\n")
    parts.append(
        "Only tool versions with an upstream statement covering these Kubernetes versions "
        "are listed here. Each tool's page has every recorded version.\n"
    )
    by_category = {}
    for tool in tools:
        by_category.setdefault(tool["category"], []).append(tool)
    parts.append(jump_list(by_category))
    for category, title in CATEGORY_TITLES.items():
        group = by_category.get(category)
        if not group:
            continue
        parts.append(f"## {title}\n")
        for tool in sorted(group, key=lambda t: t["title"].lower()):
            parts.append(f"### [{tool['title']}](tools/{tool['name']}.md) {{ #{tool['name']} }}\n")
            covered = in_window(current(tool["releases"]), window)
            if covered:
                parts.append(matrix_table("Version", covered, window) + "\n")
            else:
                parts.append("No recorded version has an upstream statement covering these Kubernetes versions.\n")
    return "\n".join(parts)


def write_nav(tools):
    """Refresh the site navigation in zensical.toml between its two marker lines."""
    begin, end = "# BEGIN generated nav", "# END generated nav"
    text = SITE_CONFIG.read_text(encoding="utf-8")
    if text.count(begin) != 1 or text.count(end) != 1:
        sys.exit(f"{SITE_CONFIG.name}: expected one '{begin}' line and one '{end}' line")
    head, _, rest = text.partition(begin)
    _, _, tail = rest.partition(end)
    pages = [f'    {{ "{t["title"]}" = "tools/{t["name"]}.md" }},' for t in sorted(tools, key=lambda t: t["title"].lower())]
    nav = [
        "nav = [",
        '  { "Home" = "index.md" },',
        '  { "Compatibility matrix" = "matrix.md" },',
        '  { "How to read this" = "how-to-read.md" },',
        '  { "Tools" = [',
        *pages,
        "  ] },",
        "]",
    ]
    SITE_CONFIG.write_text(head + begin + "\n" + "\n".join(nav) + "\n" + end + tail, encoding="utf-8")


def main():
    window = load_window()
    tools = [load_yaml(path) for path in tool_files()]

    tools_dir = DOCS / "tools"
    tools_dir.mkdir(parents=True, exist_ok=True)
    for stale in tools_dir.glob("*.md"):
        stale.unlink()

    for tool in tools:
        (tools_dir / f"{tool['name']}.md").write_text(tool_page(tool, window), encoding="utf-8")
    (DOCS / "matrix.md").write_text(matrix_page(tools, window), encoding="utf-8")

    write_nav(tools)

    # each schema's $id is a URL on the site, so publish the schemas there
    (DOCS / "schema").mkdir(exist_ok=True)
    for schema in sorted(SCHEMA_FILE.parent.glob("*.schema.json")):
        shutil.copyfile(schema, DOCS / "schema" / schema.name)

    print(f"Generated docs/matrix.md and {len(tools)} tool page(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
